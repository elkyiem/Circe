import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { SOURCE_DESCRIPTORS, syncConfigFor } from "../src/sources/registry.ts";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..", "..", "..");
const outPath = join(repoRoot, "docs", "supported-sources.md");

const rows = SOURCE_DESCRIPTORS.map((d) => {
  const hosts = d.hosts.map((h) => `\`${h}\``).join(", ");
  const patterns = d.urlPatterns.map((p) => `\`${p.source}\``).join("<br>");
  const strategy = syncConfigFor(d.id).strategy;
  const sync = strategy === "none" ? "—" : `\`${strategy}\``;
  const connect = `\`${d.connect ?? "session"}\``;
  return `| ${d.label} | \`${d.id}\` | ${hosts} | ${patterns} | ${sync} | ${connect} |`;
}).join("\n");

const md = `<!-- Generated by \`pnpm generate\`. Do not edit by hand. -->

# Supported sources

Pond can capture saves from the sources below. To add one, run
\`pnpm new-source <id>\` and follow [\`CONTRIBUTING.md\`](../CONTRIBUTING.md).

The **Sync** column shows how a source's saved list is walked (\`cursor\` /
\`scroll\` / \`full\`), or a dash for capture-only sources.

The **Connect** column shows how you connect an Account: \`session\` reads the
site with your signed-in session, and \`handle\` takes your public handle with
no sign-in.

| Source | Id | Hosts | URL patterns | Sync | Connect |
| --- | --- | --- | --- | --- | --- |
${rows}

\`local\` is a built-in pseudo-source for files imported directly into the
library; it has no network extractor.
`;

if (process.argv.includes("--check")) {
  const existing = readFileSync(outPath, "utf8");
  if (existing !== md) {
    throw new Error(
      "Supported sources documentation is stale. Run pnpm generate.",
    );
  }
  console.log(`verified ${outPath} (${SOURCE_DESCRIPTORS.length} sources)`);
} else {
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, md);
  console.log(`wrote ${outPath} (${SOURCE_DESCRIPTORS.length} sources)`);
}
